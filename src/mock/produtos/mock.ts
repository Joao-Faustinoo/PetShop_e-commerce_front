/**
 * RN0013: o valor de venda nasce do custo mais a margem do grupo. Fica
 * aqui, e não no service, para que o mock já nasça coerente com a regra
 * sem criar dependência circular entre mock e service.
 */
const precificar = (valorCusto: number, grupoId: number): number => {
  const grupo = mockGruposPrecificacao.find(g => g.id === grupoId);
  const margem = grupo?.margemLucro ?? 0;

  return Number((valorCusto * (1 + margem / 100)).toFixed(2));
};

